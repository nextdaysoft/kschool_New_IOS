    func setupPlanetGrid() {

        let letters = generatePlanetGrid()

        for (index, item) in planetItems.enumerated() {
            item.label.text = letters[index]
            item.label.textAlignment = .center
            item.label.textColor = .black
            item.view.backgroundColor = .white
            item.view.layer.borderWidth = 0.5
            item.view.layer.borderColor = UIColor.lightGray.cgColor
      
        }
    }
    
    
    func generatePlanetGrid() -> [String] {

        let rows = 10, cols = 10
        var grid = Array(repeating: "", count: rows * cols)
        planetWordIndexes.removeAll()

        for planet in planets {

            let chars = Array(planet)
            var placed = false

            while !placed {

                let startRow = Int.random(in: 0..<rows)
                let startCol = Int.random(in: 0..<cols)
                let horizontal = Bool.random()

                if horizontal && startCol + chars.count > cols { continue }
                if !horizontal && startRow + chars.count > rows { continue }

                var indexes: [Int] = []
                var conflict = false

                for i in 0..<chars.count {
                    let row = horizontal ? startRow : startRow + i
                    let col = horizontal ? startCol + i : startCol
                    let index = row * cols + col

                    if !grid[index].isEmpty {
                        conflict = true
                        break
                    }
                    indexes.append(index)
                }

                if conflict { continue }

                for (i, index) in indexes.enumerated() {
                    grid[index] = String(chars[i])
                }

                planetWordIndexes[planet] = indexes
                placed = true
            }
        }

        let selectedLanguage = UserDefaults.standard.string(forKey: "selectedLanguage") ?? "en"

        let randomCharacters: String

        if selectedLanguage == "zhHans" {
            randomCharacters = """
            的一是在不了有人和国中大为上个这我以要他时来用们生到作地于出就分对成会可主发年动同工也能下过子说产种面而方后多定行学法所民得经十三之进着等部度家电力里如水化高自二理起小物现实加量都两体制机当使点从业本去把性好应开它合还因由其些然前外天政四日那社义事平形相全表间样与关各重新线内数正心反你明看原又么利比或但质气第向道命此变条只没结解问意建月公无系军很情者最立代想已通并提直题党程展五果料象员革位入常文总次品式活设及管特件长求老头基资边流路级少图山统接知较将组见计别她手角期根论运农指几九区强放决西被干做必战先回则任取据处理世车价
            """
        } else {
            randomCharacters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
        }

        for i in 0..<grid.count where grid[i].isEmpty {
            grid[i] = String(randomCharacters.randomElement()!)
        }

        return grid
    }
    
    @objc func handlePlanetPan(_ gesture: UIPanGestureRecognizer) {

        let location = gesture.location(in: view)

        for item in planetItems {

            let point = item.view.convert(location, from: view)

            if item.view.bounds.contains(point),
               !selectedPlanetItems.contains(where: { $0.view == item.view }),
               !lockedPlanetViews.contains(item.view) {

                if currentPlanetColor == nil {
                    currentPlanetColor = customPurpleColor
                }

                selectedPlanetItems.append(item)
                formedPlanetWord += item.label.text ?? ""

                item.view.backgroundColor = currentPlanetColor!
                item.label.textColor = .white
            }
        }

        if gesture.state == .ended {
            checkPlanetWord()
        }
    }
    
    func checkPlanetWord() {

        let word = formedPlanetWord.uppercased()
        let reversedWord = String(word.reversed())

        if (planets.contains(word) || planets.contains(reversedWord)),
           !(foundPlanets.contains(word) || foundPlanets.contains(reversedWord)) {

            let correctWord = planets.contains(word)
                ? word
                : reversedWord

            foundPlanets.insert(correctWord)

            let finalColor =
                selectionColors[usedColorIndex % selectionColors.count]

            for item in selectedPlanetItems {
                lockedPlanetViews.insert(item.view)
                item.view.backgroundColor = finalColor
                item.label.textColor = .white
            }

            usedColorIndex += 1
            score += 1

            scoreLabel.text = "\("Score".localiz()): \(score) / \(planets.count)"

        } else {

            for item in selectedPlanetItems {
                item.view.backgroundColor = .white
                item.label.textColor = .black
            }
        }

        formedPlanetWord = ""
        selectedPlanetItems.removeAll()
        currentPlanetColor = nil

        if foundPlanets.count == planets.count {

            UserDefaults.standard.set(
                true,
                forKey: "wordSearchLevel4Completed"
            )

            showPlanetCompletion()
        }
    }
    
