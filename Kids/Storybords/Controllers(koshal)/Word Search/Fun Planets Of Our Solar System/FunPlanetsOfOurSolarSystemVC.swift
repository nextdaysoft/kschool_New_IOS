                where: { $0 is WordSearchMenuVC }
            ) as? WordSearchMenuVC {
                menuVC.level4Completed = true
            }

            navigationController?.popViewController(animated: true)
            return
        }

        guard let pending = planets.first(where: { !foundPlanets.contains($0) }),
              let index = planetWordIndexes[pending]?.first else { return }

        let item = planetItems[index]

        if !lockedPlanetViews.contains(item.view) {
            flashlockedPlanetItem(item, color: customPurpleColor)
        }
    }
    
    
    @IBAction func pdfTapBtn(_ sender: UIButton) {

        guard let pdfURL = createPDF() else { return }

        let activityVC = UIActivityViewController(
            activityItems: [pdfURL],
            applicationActivities: nil
        )

        if let popover = activityVC.popoverPresentationController {
            popover.sourceView = sender
        }

        present(activityVC, animated: true)
    }
    
