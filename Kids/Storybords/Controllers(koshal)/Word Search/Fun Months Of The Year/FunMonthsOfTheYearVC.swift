    func setupGrid() {

        let letters = generateGridLetters()

        for i in 0..<monthItems.count {

            if i < letters.count {
                monthItems[i].label.text = letters[i]
            } else {
                monthItems[i].label.text = ""
            }

            monthItems[i].view.backgroundColor = .white
            monthItems[i].label.textColor = .black
        }
    }

    func generateGridLetters() -> [String] {

        let rows = 12
        let cols = 10
        let total = rows * cols

        var grid = Array(repeating: "", count: total)
        monthIndexes.removeAll()

        for month in months {

            let chars = Array(month)
            var placed = false

            while !placed {

                let startRow = Int.random(in: 0..<rows)
                let startCol = Int.random(in: 0..<(cols - chars.count + 1))

                var indexes: [Int] = []
                var conflict = false

                for i in 0..<chars.count {
                    let index = startRow * cols + startCol + i

                    if !grid[index].isEmpty {
                        conflict = true
                        break
                    }
                    indexes.append(index)
                }

                if conflict { continue }

                for (i, idx) in indexes.enumerated() {
                    grid[idx] = String(chars[i])
                }

                monthIndexes[month] = indexes
                placed = true
            }
        }

        let selectedLanguage = UserDefaults.standard.string(forKey: "selectedLanguage") ?? "en"

        let randomCharacters: String

        if selectedLanguage == "zhHans" {
            randomCharacters = """
            的一是在不了有人和国中大为上个这我以要他时来用们生到作地于出就分对成会可主发年动同工也能下过子说产种面而方后多定行学法所民得经十三之进着等部度家电力里如水化高自二理起小物现实加量都两体制机当使点从业本去把性好应开它合还因由其些然前外天政四日那社义事平形相全表间样与关各重新线内数正心反你明看原又么利比或但质气第向道命此变条只没结解问意建月公无系军很情者最立代想已通并提直题党程展五果料象员革位入常文总次品式活设及管特件长求老头基资边流路级少图山统接知较将组见计别她手角期根论运农指几九区强放决西被干做必战先回则任取据处理世车价
            """
        } else {
            randomCharacters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
        }

        for i in 0..<grid.count where grid[i].isEmpty {
            grid[i] = String(randomCharacters.randomElement()!)
        }

        return grid
    }

    @objc func handlePan(_ gesture: UIPanGestureRecognizer) {
        let loc = gesture.location(in: view)

        for item in monthItems {
            let p = item.view.convert(loc, from: view)
            if item.view.bounds.contains(p),
               !selectedItems.contains(where: {$0.view == item.view}),
               !lockedViews.contains(item.view) {

                if currentColor == nil {
                    currentColor = customPurpleColor
                }

                selectedItems.append(item)
                formedWord += item.label.text ?? ""
                item.view.backgroundColor = currentColor!
                item.label.textColor = .white
            }
        }

        if gesture.state == .ended {
            checkWord()
        }
    }

    func checkWord() {

        let word = formedWord.uppercased()
        let reversedWord = String(word.reversed())

        if (months.contains(word) || months.contains(reversedWord)),
           !(foundMonths.contains(word) || foundMonths.contains(reversedWord)) {

            let correctWord = months.contains(word)
                ? word
                : reversedWord

            foundMonths.insert(correctWord)

            let finalColor =
                colors[usedColorIndex % colors.count]

            selectedItems.forEach {
                lockedViews.insert($0.view)
                $0.view.backgroundColor = finalColor
                $0.label.textColor = .white
            }

            usedColorIndex += 1

            scoreLabel.text = "\("Score".localiz()): \(foundMonths.count) / \(months.count)"

        } else {

            selectedItems.forEach {
                $0.view.backgroundColor = .white
                $0.label.textColor = .black
            }
        }

        formedWord = ""
        selectedItems.removeAll()
        currentColor = nil

        if foundMonths.count == months.count {

            didCompleteGame = true

            UserDefaults.standard.set(
                true,
                forKey: "wordSearchLevel3Completed"
            )

            showCompletion()
        }
    }

    func showCompletion() {
        hintAndNextBtn.setTitle("Next".localiz(), for: .normal)
        scoreLabel.text = "Good Job!".localiz()
        scoreLabel.textColor = .white
        scoreLabel.font = UIFont.boldSystemFont(ofSize: 20)
        scoreLabelBGView.backgroundColor = colors.randomElement()
    }
    
    func flashlockedItem(_ item: MonthLetterItem, color: UIColor) {
        UIView.animate(withDuration: 0.25, animations: {
            item.view.backgroundColor = color
            item.label.textColor = .white
        }) { _ in
            UIView.animate(withDuration: 0.25, delay: 0.4, options: [], animations: {
                if !self.lockedViews.contains(item.view) {
                    item.view.backgroundColor = .white
                    item.label.textColor = .black
                }
            })
        }
    }
    
    @IBAction func hintAndNextTapBtn(_ sender: UIButton) {

        if didCompleteGame {

            if let menuVC = navigationController?.viewControllers.first(
                where: { $0 is WordSearchMenuVC }
            ) as? WordSearchMenuVC {

                menuVC.level3Completed = true
            }

            navigationController?.popViewController(animated: true)
            return
        }

        guard let currentMonth = months.first(where: { !foundMonths.contains($0) }),
              let indexes = monthIndexes[currentMonth],
              let firstIndex = indexes.first else { return }

        let item = monthItems[firstIndex]
        
        if !lockedViews.contains(item.view) {
            flashlockedItem(item, color: customPurpleColor)
        }
    }
