    // MARK: - GRID SETUP
    func setupDayGrid() {
        let letters = generateDayGridLetters()

        for i in 0..<dayItems.count {
            dayItems[i].label.text = i < letters.count ? letters[i] : ""
            dayItems[i].view.backgroundColor = .white
            dayItems[i].label.textColor = .black
        }
    }

    func generateDayGridLetters() -> [String] {

        let rows = 10
        let cols = 10
        let total = rows * cols

        var grid = Array(repeating: "", count: total)
        dayIndexes.removeAll()

        for day in days {

            let chars = Array(day)
            var placed = false

            while !placed {
                let row = Int.random(in: 0..<rows)
                let col = Int.random(in: 0..<(cols - chars.count + 1))

                var indexes: [Int] = []
                var conflict = false

                for i in 0..<chars.count {
                    let index = row * cols + col + i

                    if !grid[index].isEmpty {
                        conflict = true
                        break
                    }

                    indexes.append(index)
                }

                if conflict { continue }

                for (i, idx) in indexes.enumerated() {
                    grid[idx] = String(chars[i])
                }

                dayIndexes[day] = indexes
                placed = true
            }
        }

        // ✅ Language based random characters

        let selectedLanguage = UserDefaults.standard.string(forKey: "selectedLanguage") ?? "en"

        let randomCharacters: String

        if selectedLanguage == "zhHans" {
            randomCharacters = "星期一二三四五六日年月天地中国人民学习学校老师学生水果动物颜色数字身体家庭朋友天气电脑手机音乐快乐健康阅读写字游戏"
        } else {
            randomCharacters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
        }

        for i in 0..<grid.count where grid[i].isEmpty {
            grid[i] = String(randomCharacters.randomElement()!)
        }

        return grid
    }

    // MARK: - PAN GESTURE
    @objc func handleDayPan(_ gesture: UIPanGestureRecognizer) {
        let location = gesture.location(in: view)

        for item in dayItems {
            let point = item.view.convert(location, from: view)

            if item.view.bounds.contains(point),
               !selectedDayItems.contains(where: { $0.view == item.view }),
               !lockedDayViews.contains(item.view) {

                if currentColor == nil {
                    currentColor = customPurpleColor
                }

                selectedDayItems.append(item)
                formedDayWord += item.label.text ?? ""
                item.view.backgroundColor = currentColor!
                item.label.textColor = .white
            }
        }

        if gesture.state == .ended {
            checkDayWord()
        }
    }

    // MARK: - WORD CHECK
    func checkDayWord() {

        let word = formedDayWord.uppercased()
        let reversedWord = String(word.reversed())

        if (days.contains(word) || days.contains(reversedWord)),
           !(foundDays.contains(word) || foundDays.contains(reversedWord)) {

            let correctWord = days.contains(word) ? word : reversedWord

            foundDays.insert(correctWord)

            let finalColor = colors[usedColorIndex % colors.count]

            selectedDayItems.forEach {
                lockedDayViews.insert($0.view)
                $0.view.backgroundColor = finalColor
                $0.label.textColor = .white
            }

            usedColorIndex += 1
            scoreLabel.text = "\("Score".localiz()): \(foundDays.count) / \(days.count)"

        } else {

            selectedDayItems.forEach {
                $0.view.backgroundColor = .white
                $0.label.textColor = .black
            }
        }

        formedDayWord = ""
        selectedDayItems.removeAll()
        currentColor = nil

        if foundDays.count == days.count {
            didCompleteGame = true

            UserDefaults.standard.set(
                true,
                forKey: "wordSearchLevel1Completed"
            )

            showDayCompletion()
        }
    }

    func showDayCompletion() {
        hintAndNextBtn.setTitle("Next".localiz(), for: .normal)
        scoreLabel.text = "Good Job!".localiz()
        scoreLabel.textColor = .white
        scoreLabel.font = UIFont.boldSystemFont(ofSize: 20)
        scoreLabelBGView.backgroundColor = colors.randomElement()
    }
    
    func flashlockedDayItem(_ item: DayLetterItem, color: UIColor) {
        UIView.animate(withDuration: 0.25, animations: {
            item.view.backgroundColor = color
            item.label.textColor = .white
        }) { _ in
            UIView.animate(withDuration: 0.25, delay: 0.4, options: [], animations: {
                if !self.lockedDayViews.contains(item.view) {
                    item.view.backgroundColor = .white
                    item.label.textColor = .black
                }
            })
        }
    }
    
    // MARK: - HINT / NEXT
    @IBAction func hintAndNextTapBtn(_ sender: UIButton) {

        if didCompleteGame {
            if let menuVC = navigationController?.viewControllers.first(
                where: { $0 is WordSearchMenuVC }
            ) as? WordSearchMenuVC {
                menuVC.level1Completed = true
            }

            navigationController?.popViewController(animated: true)
            return
        }

        guard let nextDay = days.first(where: { !foundDays.contains($0) }),
              let indexes = dayIndexes[nextDay],
              let firstIndex = indexes.first else { return }

        let item = dayItems[firstIndex]
        if !lockedDayViews.contains(item.view) {
            flashlockedDayItem(item, color: customPurpleColor)
        }
    }
